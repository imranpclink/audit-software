const BN_DIGITS = '০১২৩৪৫৬৭৮৯';

function AUDIT_i18n(lang) {
  const bn = lang === 'bn';
  const digits = (s) => (bn ? String(s).replace(/[0-9]/g, (d) => BN_DIGITS[d]) : String(s));
  return {
    lang,
    t: (s) => (bn ? AUDIT_BN[s] || s : s),
    st: (code) => {
      const l = AUDIT_STATUS_LABEL[code];
      return l ? l[bn ? 1 : 0] : String(code || '').replace(/_/g, ' ').toLowerCase();
    },
    nm: (row, field = 'name') => (row ? (bn ? row[`${field}_bn`] || row[`${field}_en`] : row[`${field}_en`]) : ''),
    num: (v) => digits(v === null || v === undefined || v === '' ? '' : Number(v).toLocaleString('en-IN', { maximumFractionDigits: 2 })),
    money: (v) => digits(Number(v || 0).toLocaleString('en-IN', { minimumFractionDigits: 0, maximumFractionDigits: 2 })),
    date: (d) => {
      if (!d) return '';
      const [y, m, day] = String(d).slice(0, 10).split('-');
      return digits(`${day}-${m}-${y}`);
    },
    digits,
  };
}

module.exports = { AUDIT_i18n, AUDIT_BN, AUDIT_STATUS_LABEL };
